/* HardFault 诊断 C 处理器: naked handler 已把 r0 设为故障栈指针(异常帧地址).
 * 异常帧布局(无 FPU 压栈): sp[0..7] = r0,r1,r2,r3,r12,lr,pc,xpsr */
void HardFault_Handler_C(uint32_t *sp)
{
  crash_log[0] = 0xDEAD0003;      /* HardFault 标记 */
  crash_log[1] = SCB->CFSR;       /* 配置/用法故障状态 */
  crash_log[2] = SCB->HFSR;       /* 硬故障状态 */
  crash_log[3] = sp[6];           /* PC (故障指令地址) */
  crash_log[4] = sp[5];           /* LR (调用者) */
  crash_log[5] = sp[0];           /* R0 */
  crash_log[6] = sp[1];           /* R1 */
  crash_log[7] = sp[2];           /* R2 */
  HAL_GPIO_WritePin(GPIOB, GPIO_PIN_0, GPIO_PIN_RESET);
  while (1) {}
}
